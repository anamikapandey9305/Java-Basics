package BasicsOfJava;

public class precentageof5 {
    public static void main(String[] args) {
        // code for calculating percentage
        double x1 = 90;  //x1 can be physics
        double x2 = 61;  //x2 can be chemistry
        double x3 = 73;  //x3 maths
        double x4 = 58;  // x4 english
        double x5 = 76;  //  x5 bio

        double percentage = (x1+ x2+ x3+ x4+ x5)/5;
        System.out.println(percentage);

    }
}
