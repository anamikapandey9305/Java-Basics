package Loops;

public class dowhile {
    public static void main(String[] args) {
        int i = 1;

        do {
            System.out.println(i);
            i++;  // increment i
        } while (i <= 5);
        // do while loop
       /*
       In do while loop - code block is executeed at least once even if the condition is false.

         do {
    // Code to execute
} while (condition);

The body inside do { } executes first.

Then the condition is checked:

If the condition is true, the loop repeats.

If the condition is false, the loop stops.

Notice the semicolon (;) at the end of the while statement — this is mandatory.



do-while loop is useful when you need to run a loop at least once, regardless of the condition.
        */


























































    }
}
