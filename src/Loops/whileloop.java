package Loops;

public class whileloop {
    public static void main(String[] args) {
        int i =1;
        while(i<=5){
            System.out.println(i+ " ");
            i++;
        }
    }


}
/*
nitially, i = 1

Condition i <= 5 → true → print i

After printing, i++ increases i by 1

This repeats until i becomes 6, then the loop stop
 */
