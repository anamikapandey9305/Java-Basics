package Stringss;

public class EndsWith {
    public static void main(String[] args) {

        String name = "Anamika Pandey";

        // checks whether String ends with "Pandey"
        System.out.println(name.endsWith("Pandey"));

        // checks whether String ends with "Anamika"
        System.out.println(name.endsWith("Anamika"));
    }
}