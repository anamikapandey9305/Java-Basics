package Stringss;

public class StartsWith {
    public static void main(String[] args) {

        String name = "Anamika Pandey";

        // checks whether String starts with "Anamika"
        System.out.println(name.startsWith("Anamika"));

        // checks whether String starts with "Pandey"
        System.out.println(name.startsWith("Pandey"));
    }
}